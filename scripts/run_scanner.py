"""Run the relative-value scanner over all analysed cases: reports/scanner.json and reports/scanner.md."""
from __future__ import annotations

import json
from pathlib import Path

from creditlab.scanner import run

ROOT = Path(__file__).resolve().parents[1]


def fmt(v, unit):
    if unit == "probability":
        return f"{v:+.0%}"
    if unit == "x":
        return f"{v:.2f}x"
    if unit == "bp":
        return f"{v:+.0f}bp"
    return f"{v:+.2f} pts"


def main():
    sigs = run(ROOT)
    (ROOT / "reports" / "scanner.json").write_text(json.dumps(sigs, indent=1), encoding="utf-8")
    lines = ["# Relative-value scanner", "",
             "Generated by `scripts/run_scanner.py` from the case analyses. Signals are candidates for research, "
             "ranked by size discounted for their risk flags. None is an arbitrage: every row lists what can keep the gap "
             "open or widen it. Flag definitions are in `src/creditlab/scanner.py`.", "",
             "| # | Issuer | Type | Long | Short | Signal | Confidence | Flags |", "|---|---|---|---|---|---|---|---|"]
    for i, s in enumerate(sigs, 1):
        lines.append(f"| {i} | {s['issuer']} | {s['kind']} | {s['long']} | {s['short']} | {fmt(s['value'], s['unit'])} | "
                     f"{s['confidence']} | {', '.join(s['flags']) or '-'} |")
    lines += ["", "## Readings", ""]
    for i, s in enumerate(sigs, 1):
        lines.append(f"{i}. **{s['issuer']}, {s['kind']}.** {s['read']}")
    (ROOT / "reports" / "scanner.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(sigs)} signals -> reports/scanner.md")
    for s in sigs[:12]:
        print(f"{s['score']:.2f} {s['confidence']:<6} {s['issuer'][:18]:<18} {s['kind']:<18} {fmt(s['value'], s['unit']):>10}  {s['long'][:26]} / {s['short'][:26]}")


if __name__ == "__main__":
    main()
